use std::path::{Path, PathBuf};

/// A workload that prints a valid record. `fast` lowers its wall time; `fail` exits unsuccessfully; `slow` creates the file named by the next argument, if any, and then sleeps for 30 seconds.
const MAIN: &str = r##"fn main() {
    let arguments: Vec<String> = std::env::args().collect();
    if arguments.iter().any(|argument| argument == "fail") {
        std::process::exit(3);
    }
    if arguments.iter().any(|argument| argument == "needs-extra") && !cfg!(feature = "extra") {
        std::process::exit(4);
    }
    if let Some(index) = arguments.iter().position(|argument| argument == "slow") {
        if let Some(marker) = arguments.get(index + 1) {
            std::fs::write(marker, "").unwrap();
        }
        std::thread::sleep(std::time::Duration::from_secs(30));
    }
    let wall = if arguments.iter().any(|argument| argument == "fast") { 900 } else { 1000 };
    println!(r#"{{"schema":"base-benchmark/process-record","version":1,"workload":"fixture","parameters":{{}},"signature":"same","samples":[{{"operations":10,"metrics":[{{"name":"wall_time","unit":"nanoseconds","phase":"measured","source":"wall","direction":"lower_is_better","measurement":{{"kind":"total","value":{wall}}}}}]}}]}}"#);
}
"##;

const MANIFEST: &str = r#"[package]
name = "fixture"
version = "0.1.0"
edition = "2021"
publish = false

[features]
extra = []

[[package.metadata.base-benchmark.scenario]]
name = "work"
smoke-arguments = ["smoke"]
variants = [{ name = "reference" }, { name = "fast", arguments = ["fast"] }]
"#;

const LOCKFILE: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n";

/// Create a minimal workload workspace at `path`, with extra scenario TOML appended.
pub fn workspace(path: &Path, extra: &str) -> PathBuf {
    std::fs::create_dir_all(path.join("src")).unwrap();
    std::fs::write(path.join("Cargo.toml"), format!("{MANIFEST}{extra}")).unwrap();
    std::fs::write(path.join("Cargo.lock"), LOCKFILE).unwrap();
    std::fs::write(path.join("src/main.rs"), MAIN).unwrap();
    path.join("Cargo.toml")
}

/// A workspace whose workload package is the member `bench`, printing `wall` nanoseconds for 10 operations. With `helper`, the workload also depends on a path package inside its own directory, so a tree whose lockfile lacks it can build this workload only unlocked.
pub fn member_workspace(path: &Path, wall: u64, helper: bool) -> PathBuf {
    let bench = path.join("bench");
    std::fs::create_dir_all(bench.join("src")).unwrap();
    std::fs::write(
        path.join("Cargo.toml"),
        "[workspace]\nmembers = [\"bench\"]\nresolver = \"2\"\n",
    )
    .unwrap();
    let locked = if helper {
        "[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\ndependencies = [\n \"helper\",\n]\n\n[[package]]\nname = \"helper\"\nversion = \"0.1.0\"\n"
    } else {
        "[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n"
    };
    std::fs::write(
        path.join("Cargo.lock"),
        format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n{locked}"),
    )
    .unwrap();
    let dependency = if helper {
        std::fs::create_dir_all(bench.join("helper/src")).unwrap();
        std::fs::write(
            bench.join("helper/Cargo.toml"),
            "[package]\nname = \"helper\"\nversion = \"0.1.0\"\nedition = \"2021\"\npublish = false\n",
        )
        .unwrap();
        std::fs::write(
            bench.join("helper/src/lib.rs"),
            "pub const WALL: u64 = 1;\n",
        )
        .unwrap();
        "[dependencies]\nhelper = { path = \"helper\" }\n"
    } else {
        ""
    };
    std::fs::write(
        bench.join("Cargo.toml"),
        format!(
            "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\npublish = false\n{dependency}\n[[package.metadata.base-benchmark.scenario]]\nname = \"work\"\n"
        ),
    )
    .unwrap();
    std::fs::write(
        bench.join("src/main.rs"),
        format!(
            r##"fn main() {{
    println!(r#"{{{{"schema":"base-benchmark/process-record","version":1,"workload":"fixture","parameters":{{{{}}}},"samples":[{{{{"operations":10,"metrics":[{{{{"name":"wall_time","unit":"nanoseconds","phase":"measured","source":"wall","direction":"lower_is_better","measurement":{{{{"kind":"total","value":{wall}}}}}}}}}]}}}}]}}}}"#);
}}
"##
        ),
    )
    .unwrap();
    path.join("Cargo.toml")
}

/// Commit everything in `path` to a new Git repository.
pub fn commit(path: &Path) {
    for arguments in [
        &["init", "--quiet"][..],
        &["add", "."],
        &[
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.com",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "--quiet",
            "-m",
            "Fixture.",
        ],
    ] {
        let status = std::process::Command::new("git")
            .arg("-C")
            .arg(path)
            .args(arguments)
            .status()
            .unwrap();
        assert!(status.success());
    }
}
